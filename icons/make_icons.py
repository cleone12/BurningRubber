#!/usr/bin/env python3
"""Regenerate the platform icons from icons/BurningRubber.png (needs Pillow).

    python3 icons/make_icons.py

The 32x32 source is pixel art, so the larger sizes are scaled up with
nearest-neighbour to keep the pixels sharp.
"""
import os
from PIL import Image

here = os.path.dirname(os.path.abspath(__file__))
src = Image.open(os.path.join(here, "BurningRubber.png")).convert("RGBA")


def scaled(size):
    return src.resize((size, size), Image.NEAREST)


# macOS app bundle
icns = [scaled(s) for s in (1024, 512, 256, 128, 64, 32, 16)]
icns[0].save(os.path.join(here, "BurningRubber.icns"), append_images=icns[1:])

# Windows executable
ico_sizes = [(s, s) for s in (256, 128, 64, 48, 32, 16)]
scaled(256).save(os.path.join(here, "BurningRubber.ico"), sizes=ico_sizes,
                 append_images=[scaled(w) for w, _ in ico_sizes[1:]])

# Window icon set at runtime (Linux, Windows title bar)
w, h = src.size
data = src.tobytes()
with open(os.path.join(here, "..", "src", "icon.h"), "w") as f:
    f.write("/* Generated by icons/make_icons.py from icons/BurningRubber.png. */\n")
    f.write("#define ICON_W %d\n#define ICON_H %d\n" % (w, h))
    f.write("static const unsigned char kIconRGBA[%d] = {\n" % len(data))
    for i in range(0, len(data), 16):
        f.write("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
    f.write("};\n")
